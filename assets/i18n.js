(function () {
  'use strict';
  var STORAGE_KEY = 'site-lang';
  var dict = window.SITE_I18N;
  var lang = localStorage.getItem(STORAGE_KEY) || 'tr';
  if (lang !== 'tr' && lang !== 'en') lang = 'tr';

  function t(key) {
    var pack = dict[lang] || dict.tr;
    return pack[key] != null ? pack[key] : (dict.tr[key] || key);
  }

  function apply() {
    document.documentElement.lang = lang;
    document.title = t('pageTitle');
    var meta = document.querySelector('meta[name="description"]');
    if (meta) meta.setAttribute('content', t('pageDesc'));

    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var key = el.getAttribute('data-i18n');
      if (!key) return;
      el.textContent = t(key);
    });
    document.querySelectorAll('[data-i18n-html]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-html');
      if (!key) return;
      el.innerHTML = t(key);
    });
    document.querySelectorAll('[data-i18n-aria]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-aria');
      if (!key) return;
      el.setAttribute('aria-label', t(key));
    });

    document.querySelectorAll('[data-lang-btn]').forEach(function (btn) {
      var active = btn.getAttribute('data-lang-btn') === lang;
      btn.classList.toggle('active', active);
      btn.setAttribute('aria-pressed', active ? 'true' : 'false');
    });

    window.dispatchEvent(new CustomEvent('site-lang-change', { detail: { lang: lang, roles: t('roles') } }));
  }

  function setLang(next) {
    if (next !== 'tr' && next !== 'en') return;
    lang = next;
    localStorage.setItem(STORAGE_KEY, lang);
    apply();
  }

  window.SiteLang = { get: function () { return lang; }, set: setLang, t: t, apply: apply };

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', function () {
      document.querySelectorAll('[data-lang-btn]').forEach(function (btn) {
        btn.addEventListener('click', function () { setLang(btn.getAttribute('data-lang-btn')); });
      });
      apply();
    });
  } else {
    document.querySelectorAll('[data-lang-btn]').forEach(function (btn) {
      btn.addEventListener('click', function () { setLang(btn.getAttribute('data-lang-btn')); });
    });
    apply();
  }
})();
